package dev.roomlock.notification.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import java.time.Instant;
import java.util.Objects;
import java.util.Optional;
import java.util.UUID;
import org.springframework.data.domain.Persistable;
import org.springframework.lang.Nullable;

/**
 * One delivery, recorded before it is attempted: {@link #claim} writes the row that the unique
 * {@code event_id} turns into a claim on the event, and {@link #markSent} stamps it once the sender
 * has taken the message. A row without {@code sentAt} therefore never committed (rule DB-1).
 *
 * <p>The id is generated by the application, and {@link Persistable#isNew()} tells Hibernate that a
 * fresh instance is an insert rather than a merge (the same convention as booking-service).
 */
@Entity
@Table(name = "notification")
public class Notification implements Persistable<UUID> {

  @Id private UUID id;

  @Column(name = "event_id", nullable = false, updatable = false)
  private UUID eventId;

  @Column(name = "event_type", nullable = false, updatable = false, length = 32)
  private String eventType;

  @Column(name = "booking_id", nullable = false, updatable = false)
  private UUID bookingId;

  @Column(name = "guest_id", nullable = false, updatable = false)
  private UUID guestId;

  @Enumerated(EnumType.STRING)
  @Column(name = "kind", nullable = false, updatable = false, length = 16)
  private NotificationKind kind;

  @Enumerated(EnumType.STRING)
  @Column(name = "channel", nullable = false, updatable = false, length = 16)
  private NotificationChannel channel;

  @Column(name = "subject", nullable = false, updatable = false, length = 200)
  private String subject;

  @Column(name = "body", nullable = false, updatable = false, length = 1000)
  private String body;

  @Column(name = "occurred_at", nullable = false, updatable = false)
  private Instant occurredAt;

  @Column(name = "handled_at", nullable = false, updatable = false)
  private Instant handledAt;

  @Nullable
  @Column(name = "sent_at")
  private Instant sentAt;

  @Transient private boolean newEntity;

  protected Notification() {}

  private Notification(
      UUID id,
      UUID eventId,
      String eventType,
      GuestNotification message,
      NotificationChannel channel,
      Instant occurredAt,
      Instant handledAt) {
    this.id = id;
    this.eventId = Objects.requireNonNull(eventId, "eventId");
    this.eventType = Objects.requireNonNull(eventType, "eventType");
    this.bookingId = message.bookingId();
    this.guestId = message.guestId();
    this.kind = message.kind();
    this.channel = Objects.requireNonNull(channel, "channel");
    this.subject = message.subject();
    this.body = message.body();
    this.occurredAt = Objects.requireNonNull(occurredAt, "occurredAt");
    this.handledAt = Objects.requireNonNull(handledAt, "handledAt");
    this.newEntity = true;
  }

  /**
   * Claims the event for delivery: the insert fails if another delivery of the same {@code eventId}
   * is already recorded.
   */
  public static Notification claim(
      UUID eventId,
      String eventType,
      GuestNotification message,
      NotificationChannel channel,
      Instant occurredAt,
      Instant handledAt) {
    return new Notification(
        UUID.randomUUID(), eventId, eventType, message, channel, occurredAt, handledAt);
  }

  /** Records that the sender accepted the message. */
  public void markSent(Instant at) {
    this.sentAt = Objects.requireNonNull(at, "at");
  }

  @Override
  public UUID getId() {
    return id;
  }

  public UUID getEventId() {
    return eventId;
  }

  public String getEventType() {
    return eventType;
  }

  public UUID getBookingId() {
    return bookingId;
  }

  public UUID getGuestId() {
    return guestId;
  }

  public NotificationKind getKind() {
    return kind;
  }

  public NotificationChannel getChannel() {
    return channel;
  }

  public String getSubject() {
    return subject;
  }

  public String getBody() {
    return body;
  }

  public Instant getOccurredAt() {
    return occurredAt;
  }

  public Instant getHandledAt() {
    return handledAt;
  }

  /** When the sender took the message; empty while the delivery has not happened. */
  public Optional<Instant> getSentAt() {
    return Optional.ofNullable(sentAt);
  }

  @Override
  public boolean isNew() {
    return newEntity;
  }

  @PostPersist
  @PostLoad
  void markNotNew() {
    newEntity = false;
  }

  @Override
  public boolean equals(Object other) {
    return this == other
        || (other instanceof Notification notification && id.equals(notification.getId()));
  }

  @Override
  public int hashCode() {
    return id.hashCode();
  }
}
