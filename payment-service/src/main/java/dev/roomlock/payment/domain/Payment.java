package dev.roomlock.payment.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import java.time.Instant;
import java.util.Objects;
import java.util.Optional;
import java.util.UUID;
import org.springframework.data.domain.Persistable;
import org.springframework.lang.Nullable;

/**
 * The one payment of a booking: the answer the service gave the first time the booking was charged,
 * kept so that every later call can be answered with it (rule I-1).
 *
 * <p>The status never changes through the entity (rule DB-5): the insert is conditional on the
 * booking id being free and the refund is a conditional {@code UPDATE}, so two concurrent calls
 * cannot both win. The amount is in minor units, as the gRPC contract sends it.
 *
 * <p>The id is generated by the application, and {@link Persistable#isNew()} tells Hibernate that a
 * fresh instance is an insert rather than a merge (the same convention as booking-service).
 */
@Entity
@Table(name = "payment")
public class Payment implements Persistable<UUID> {

  @Id private UUID id;

  @Column(name = "booking_id", nullable = false, updatable = false)
  private UUID bookingId;

  @Column(name = "guest_id", nullable = false, updatable = false)
  private UUID guestId;

  @Column(name = "amount_minor", nullable = false, updatable = false)
  private long amountMinor;

  @Column(name = "currency", nullable = false, updatable = false, length = 3)
  private String currency;

  @Enumerated(EnumType.STRING)
  @Column(name = "status", nullable = false, length = 16)
  private PaymentStatus status;

  @Nullable
  @Column(name = "decline_reason", updatable = false, length = 200)
  private String declineReason;

  @Column(name = "charged_at", nullable = false, updatable = false)
  private Instant chargedAt;

  @Nullable
  @Column(name = "refunded_at")
  private Instant refundedAt;

  @Transient private boolean newEntity;

  protected Payment() {}

  private Payment(
      UUID bookingId,
      UUID guestId,
      long amountMinor,
      String currency,
      PaymentStatus status,
      @Nullable String declineReason,
      Instant chargedAt) {
    this.id = UUID.randomUUID();
    this.bookingId = Objects.requireNonNull(bookingId, "bookingId");
    this.guestId = Objects.requireNonNull(guestId, "guestId");
    this.amountMinor = positive(amountMinor);
    this.currency = Objects.requireNonNull(currency, "currency");
    this.status = status;
    this.declineReason = declineReason;
    this.chargedAt = Objects.requireNonNull(chargedAt, "chargedAt");
    this.newEntity = true;
  }

  /** An approved charge of the amount, with an application-generated id. */
  public static Payment approved(
      UUID bookingId, UUID guestId, long amountMinor, String currency, Instant chargedAt) {
    return new Payment(
        bookingId, guestId, amountMinor, currency, PaymentStatus.APPROVED, null, chargedAt);
  }

  /** A charge the decision rule refused, with the reason the caller is told (rule DB-1). */
  public static Payment declined(
      UUID bookingId,
      UUID guestId,
      long amountMinor,
      String currency,
      String declineReason,
      Instant chargedAt) {
    return new Payment(
        bookingId,
        guestId,
        amountMinor,
        currency,
        PaymentStatus.DECLINED,
        Objects.requireNonNull(declineReason, "declineReason"),
        chargedAt);
  }

  @Override
  public UUID getId() {
    return id;
  }

  public UUID getBookingId() {
    return bookingId;
  }

  public UUID getGuestId() {
    return guestId;
  }

  public long getAmountMinor() {
    return amountMinor;
  }

  public String getCurrency() {
    return currency;
  }

  public PaymentStatus getStatus() {
    return status;
  }

  /** Why the charge was refused; empty for every payment that was not declined. */
  public Optional<String> getDeclineReason() {
    return Optional.ofNullable(declineReason);
  }

  public Instant getChargedAt() {
    return chargedAt;
  }

  /** When the money went back; empty while the payment has not been refunded. */
  public Optional<Instant> getRefundedAt() {
    return Optional.ofNullable(refundedAt);
  }

  @Override
  public boolean isNew() {
    return newEntity;
  }

  @PostPersist
  @PostLoad
  void markNotNew() {
    newEntity = false;
  }

  @Override
  public boolean equals(Object other) {
    return this == other || (other instanceof Payment payment && id.equals(payment.getId()));
  }

  @Override
  public int hashCode() {
    return id.hashCode();
  }

  private static long positive(long amountMinor) {
    if (amountMinor <= 0) {
      throw new IllegalArgumentException("amountMinor has to be positive, was " + amountMinor);
    }
    return amountMinor;
  }
}
